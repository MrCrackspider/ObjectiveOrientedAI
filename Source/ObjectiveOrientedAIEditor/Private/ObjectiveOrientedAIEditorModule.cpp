#include "Modules/ModuleManager.h"

#include "EngineDefines.h"
#include "AIObjective/AIObjective.h"
#include "Templates/SubclassOf.h"
#include "VisualLogger/VisualLogger.h"
#include "GameFramework/WorldSettings.h"
#include "Kismet2/KismetEditorUtilities.h"

class FObjectiveOrientedAIEditorModule : public IModuleInterface
{
	// Begin IModuleInterface
	virtual void StartupModule() override;
	virtual void ShutdownModule() override;
	// End IModuleInterface
	
	void RegisterAutoGeneratedDefaultEvents();
};

IMPLEMENT_MODULE(FObjectiveOrientedAIEditorModule, ObjectiveOrientedAIEditor);

void FObjectiveOrientedAIEditorModule::StartupModule()
{
	RegisterAutoGeneratedDefaultEvents();
}

void FObjectiveOrientedAIEditorModule::ShutdownModule()
{
}

void FObjectiveOrientedAIEditorModule::RegisterAutoGeneratedDefaultEvents()
{
	FKismetEditorUtilities::RegisterAutoGeneratedDefaultEvent(this, UAIObjective::StaticClass(), "OnStarted");
	FKismetEditorUtilities::RegisterAutoGeneratedDefaultEvent(this, UAIObjective::StaticClass(), "OnStopped");
}
