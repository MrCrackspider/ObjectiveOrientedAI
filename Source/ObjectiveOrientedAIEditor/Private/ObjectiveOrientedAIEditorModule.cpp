class FObjectiveOrientedAIEditorModule : public IModuleInterface
{
	// Begin IModuleInterface
	virtual void StartupModule() override;
	virtual void ShutdownModule() override;
	// End IModuleInterface

	void RegisterAutoGeneratedDefaultEvents();

	/** Narrows the tag pickers of this plugin's own tag containers to the roots named in the settings */
	static void GetTagCategories(TSharedPtr<IPropertyHandle> PropertyHandle, FString& OutCategories);

	FDelegateHandle TagCategoriesHandle;
};

IMPLEMENT_MODULE(FObjectiveOrientedAIEditorModule, ObjectiveOrientedAIEditor);

void FObjectiveOrientedAIEditorModule::StartupModule()
{
	RegisterAutoGeneratedDefaultEvents();

	TagCategoriesHandle = UGameplayTagsManager::Get().OnGetCategoriesMetaFromPropertyHandle.AddStatic(
		&FObjectiveOrientedAIEditorModule::GetTagCategories);
}

void FObjectiveOrientedAIEditorModule::ShutdownModule()
{
	// The tag manager outlives this module, so a handler left behind would be called into unloaded code
	if (UObjectInitialized() && TagCategoriesHandle.IsValid())
	{
		UGameplayTagsManager::Get().OnGetCategoriesMetaFromPropertyHandle.Remove(TagCategoriesHandle);
		TagCategoriesHandle.Reset();
	}
}

void FObjectiveOrientedAIEditorModule::RegisterAutoGeneratedDefaultEvents()
{
	FKismetEditorUtilities::RegisterAutoGeneratedDefaultEvent(this, UAIObjective::StaticClass(), "OnStarted");
	FKismetEditorUtilities::RegisterAutoGeneratedDefaultEvent(this, UAIObjective::StaticClass(), "OnStopped");
}

void FObjectiveOrientedAIEditorModule::GetTagCategories(TSharedPtr<IPropertyHandle> PropertyHandle, FString& OutCategories)
{
	// Another handler has already claimed this picker. Whatever is written here replaces the property's
	// own Categories meta outright, so the first claim is left to stand
	if (!OutCategories.IsEmpty() || !PropertyHandle.IsValid())
	{
		return;
	}

	const FProperty* Property = PropertyHandle->GetProperty();
	const UStruct* OwnerStruct = Property ? Property->GetOwnerStruct() : nullptr;

	// Matched on where the property is declared, not on the object being edited. A subclass which adds
	// tag containers of its own is then left alone, and an objective's own tags are still recognized
	// whatever kind of objective is carrying them
	const UObjectiveOrientedAISettings& Settings = UObjectiveOrientedAISettings::Get();

	if (OwnerStruct == UAIObjectiveDefinition::StaticClass())
	{
		OutCategories = Settings.GetDefinitionTagRootsFilter();
	}
	else if (OwnerStruct == UAIObjective::StaticClass())
	{
		OutCategories = Settings.GetObjectiveTagRootsFilter();
	}
}
